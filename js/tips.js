// Tips con los textos del país de la persona.
export function tipsFor(region) {
  const code = region?.code || 'VE';
  const pick = (v) => (v && v.__v ? (code in v ? v[code] : v.VE) : v);
  return TIPS.map((t) => Object.fromEntries(Object.entries(t).map(([k, v]) => [k, pick(v)])));
}
